def pack_icon(accent: str, seed: int) -> Image.Image:
    s = 256
    cv = tex.Canvas(s, s)
    bg = tex.material("void", s, s, seed, [(0, "#020106"), (0.6, "#120a24"), (0.85, "#2a1650"), (1, "#7d5cd6")])
    cv.paint(0, 0, bg.rgb)
    c = s / 2
    acc = tex.hex_rgb(accent)
    gold = tex.hex_rgb("#d9a646")
    layers = [
        (tex.ring_mask(s, s, c, c, 104, 10), gold),
        (tex.ring_mask(s, s, c, c, 82, 4), acc),
        (tex.ring_mask(s, s, c, c, 44, 6), gold),
    ]
    for i in range(8):
        ang = i * np.pi / 4
        p0 = (c + np.cos(ang) * 48, c + np.sin(ang) * 48)
        p1 = (c + np.cos(ang) * 98, c + np.sin(ang) * 98)
        layers.append((tex.line_mask(s, s, p0, p1, 5), gold))
    runes = np.zeros((s, s), dtype=np.float32)
    for i in range(8):
        ang = i * np.pi / 4 + np.pi / 8
        g = tex.glyph(22, seed + i, stroke=1.4)
        x = int(c + np.cos(ang) * 64 - 11)
        y = int(c + np.sin(ang) * 64 - 11)
        runes[y:y + 22, x:x + 22] = np.maximum(runes[y:y + 22, x:x + 22], g)
    layers.append((runes, acc))
    core = tex.disc_mask(s, s, c, c, 30, soft=10)
    for m, col in layers:
        cv.paint(0, 0, np.broadcast_to(col, (s, s, 3)).copy(), m)
    glow = np.clip(1 - np.sqrt((np.mgrid[0:s, 0:s][1] - c) ** 2 + (np.mgrid[0:s, 0:s][0] - c) ** 2) / 120, 0, 1) ** 2
    cv.rgba[..., :3] = np.clip(cv.rgba[..., :3] + glow[..., None] * acc * 0.35, 0, 1)
    cv.paint(0, 0, np.broadcast_to(np.array([1.0, 1.0, 1.0]), (s, s, 3)).copy(), core)
    cv.rgba[..., 3] = 1.0
    return cv.image()


def lang_text(entries: dict[str, str]) -> str:
    lines = ["## APOCALYPSE ENGINE — English (US)"]
    for k in sorted(entries):
        lines.append(f"{k}={entries[k]}\t#")
    return "\n".join(lines) + "\n"


def ts_ids() -> str:
    out = ["// AUTO-GENERATED by tools/generate_all.py from the content definitions. Do not edit by hand.",
           "// Every identifier the scripts use comes from here, so a typo fails TypeScript compilation.", ""]
    for group in sorted(REG.ts_ids):
        out.append(f"export const {group.upper()} = {{")
        for k, v in sorted(REG.ts_ids[group].items()):
            out.append(f"  {k}: {json.dumps(v)},")
        out.append("} as const;")
        out.append("")
    return "\n".join(out)


def build():
    bp, rp = manifests()
    REG.add_bp("manifest.json", bp)
    REG.add_rp("manifest.json", rp)
    REG.images["bp:pack_icon.png"] = pack_icon("#ff2a4a", 3)
    REG.images["rp:pack_icon.png"] = pack_icon("#3ff3ff", 4)
    REG.name("pack.name", "APOCALYPSE ENGINE")
    REG.name("pack.description", "Colossal bosses, world events and a lost dimension.")
